export const messages: Record<Lang, Record<MessageKey, string>> = { es, en };

export function localeForLang(lang: Lang): "es-MX" | "en-US" {
  return lang === "en" ? "en-US" : "es-MX";
}

export function readInitialLang(): Lang {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "en" || stored === "es") return stored;
  } catch {
    // Ignore storage access errors in restricted environments
  }
  return "es";
}

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, token) =>
    Object.prototype.hasOwnProperty.call(params, token) ? String(params[token]) : match,
  );
}

export function translateMessage(
  key: MessageKey,
  lang: Lang,
  params?: Record<string, string | number>,
): string {
  const template = messages[lang]?.[key] ?? messages.es[key];
  return interpolate(template, params);
}

function makeDateFormat(lang: Lang): Intl.DateTimeFormat {
  return new Intl.DateTimeFormat(localeForLang(lang), {
    day: "2-digit",
    month: "short",
    year: "numeric",
    timeZone: "America/Mexico_City",
  });
}

export interface I18nContextValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: MessageKey, params?: Record<string, string | number>) => string;
  formatDate: (date: Date) => string;
  pick: (raw: string) => string;
  tError: (err: unknown) => string;
}

const defaultContext: I18nContextValue = {
  lang: "es",
  setLang: () => {},
  t: (key, params) => translateMessage(key, "es", params),
  formatDate: (date) => makeDateFormat("es").format(date),
  pick: (raw) => pickBilingual(raw, "es"),
  tError: (err) => formatBackendError(err, "es"),
};

const I18nContext = createContext<I18nContextValue>(defaultContext);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readInitialLang);

  function setLang(next: Lang) {
    setLangState(next);
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // Ignore storage access errors
    }
  }

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo<I18nContextValue>(() => {
    const fmt = makeDateFormat(lang);
    return {
      lang,
      setLang,
      t: (key, params) => translateMessage(key, lang, params),
      formatDate: (date) => fmt.format(date),
      pick: (raw) => pickBilingual(raw, lang),
      tError: (err) => formatBackendError(err, lang),
    };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}
