// Canonical domain wire types; no dependencies or runtime schema interpreters.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const operations = process.argv.includes("--operations");
const schema = JSON.parse(readFileSync(new URL(`../contracts/v1/project_results${operations ? "_operations" : ""}.schema.json`, import.meta.url), "utf8"));
const pascal = key => key.split("_").map(word => word[0].toUpperCase() + word.slice(1)).join("");
const names = Object.fromEntries(Object.keys(schema.$defs).map(key => [key, `${operations ? "Operations" : "Results"}${pascal(key)}`]));
function type(node) {
  if (node.$ref?.startsWith("project_results.schema.json")) return `Domain.Results${pascal(node.$ref.split("/").at(-1))}`;
  if (node.$ref?.startsWith("projects.schema.json")) return "LegacyProject";
  if (node.$ref?.startsWith("activity_operations.schema.json")) return "LegacyEvidence";
  if (node.$ref) return names[node.$ref.split("/").at(-1)];
  if (node === schema.$defs.legacy_entry) return "LegacyActivityEntry";
  if (node.anyOf) return node.anyOf.map(type).join(" | ");
  if ("const" in node) return JSON.stringify(node.const);
  if (node.enum) return node.enum.map(value => JSON.stringify(value)).join(" | ");
  if (Array.isArray(node.type)) return node.type.map(value => type({ ...node, type: value })).join(" | ");
  if (node.type === "object") return `{\n${Object.entries(node.properties).map(([key, value]) => `  ${key}${node.required?.includes(key) ? "" : "?"}: ${type(value)};`).join("\n")}\n}`;
  if (node.type === "array") return `Array<${type(node.items)}>`;
  if (node.type === "integer" || node.type === "number") return "number";
  if (["string", "boolean", "null"].includes(node.type)) return node.type;
  throw new Error(`Unsupported results schema node: ${JSON.stringify(node)}`);
}
const output = "// Generated by scripts/generate_results_types.mjs. Edit the JSON Schema, then regenerate.\n"
  + "// Structural types only. Rust validates dates, references, policy and transitions.\n\n"
  + (operations ? 'import type * as Domain from "./project-results.generated";\nimport type { Project as LegacyProject, Evidence as LegacyEvidence, ActivityEntry as LegacyActivityEntry } from "./api";\n\n' : "")
  + Object.entries(schema.$defs).map(([key, value]) => `export type ${names[key]} = ${type(value)};\n`).join("\n")
  + (operations ? "" : `\nexport type ResultsPlan = ${type(schema)};\n`);
const destination = new URL(`../src/lib/project-results${operations ? "-operations" : ""}.generated.ts`, import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8") !== output) throw new Error("Results types drift: run node scripts/generate_results_types.mjs");
  console.log("PASS: result-planning TypeScript bindings match canonical schema.");
} else {
  writeFileSync(destination, output);
  console.log(`Generated ${fileURLToPath(destination)}`);
}
